import 'package:flutter_test/flutter_test.dart';
import 'package:hub_mobile/core/vietqr/vietqr.dart';

void main() {
  // Independent reference: the standard CRC-16/CCITT-FALSE check value.
  test('crc16 of the standard check string', () {
    expect(crc16('123456789'), '29B1');
  });

  test('crc16 pads to four hex digits and is upper case', () {
    expect(crc16(''), 'FFFF');
    expect(RegExp(r'^[0-9A-F]{4}$').hasMatch(crc16('abc')), isTrue);
  });

  // Same vector as miniapps/tea-tour/tests/test_vietqr.py (branch feat/tea-tour-pro),
  // so both implementations agree. It was generated by that code, not by a bank app.
  const vector =
      '00020101021238570010A00000072701270006970405011386002010012340208QRIBFTTA530370454065000005802VN'
      '62170813TOUR K7M2QX9A6304C17A';

  test('payload equals the cross-implementation vector', () {
    expect(
      buildVietQrPayload(bankBin: '970405', account: '8600201001234', amountVnd: 500000, content: 'TOUR K7M2QX9A'),
      vector,
    );
  });

  test('payload ends with a CRC that matches its own body', () {
    final p = buildVietQrPayload(bankBin: '970436', account: '0011004567890', amountVnd: 1260000, content: 'DH 4F9K2A');
    expect(p.substring(p.length - 8, p.length - 4), '6304');
    expect(p.substring(p.length - 4), crc16(p.substring(0, p.length - 4)));
    expect(
      p,
      contains(
        '5407'
        '1260000',
      ),
    );
    expect(p, contains('0809DH 4F9K2A'));
  });

  test('bank table has 21 unique six-digit BINs', () {
    expect(banks.length, 21);
    expect({for (final b in banks) b.bin}.length, 21);
    expect(banks.every((b) => RegExp(r'^[0-9]{6}$').hasMatch(b.bin)), isTrue);
    expect(bankByBin('970405')?.name, 'Agribank');
    expect(bankByBin('000000'), isNull);
  });

  test('refuses bad input', () {
    for (final args in [
      ('97040', '8600201001234', 1000, 'TOUR A'),
      ('970405', '12345', 1000, 'TOUR A'),
      ('970405', '86002010012x4', 1000, 'TOUR A'),
      ('970405', '8600201001234', 0, 'TOUR A'),
      ('970405', '8600201001234', 1000, 'TOUR Đ'),
      ('970405', '8600201001234', 1000, 'x' * 26),
      ('970405', '8600201001234', 1000, ''),
    ]) {
      expect(
        () => buildVietQrPayload(bankBin: args.$1, account: args.$2, amountVnd: args.$3, content: args.$4),
        throwsArgumentError,
        reason: '$args',
      );
    }
  });
}
