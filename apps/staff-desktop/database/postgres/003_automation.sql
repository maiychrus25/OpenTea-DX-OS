-- Upgrade for databases created before 1.3.0: recurring tasks, automation suggestions and the automation log.
-- The app applies the same change on start-up; run this by hand only for a DX-OS install managed by migrations.

CREATE TABLE IF NOT EXISTS app_staff_work.automation_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    rule character varying(60) NOT NULL,
    message text NOT NULL,
    htx_code character varying(20) NOT NULL,
    created_at timestamp without time zone NOT NULL,
    updated_at timestamp without time zone NOT NULL,
    CONSTRAINT "PK_automation_logs" PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS app_staff_work.automation_suggestions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    kind text NOT NULL,
    status text NOT NULL,
    title character varying(240) NOT NULL,
    detail text,
    task_id integer,
    template_id integer,
    leave_id integer,
    employee_id integer,
    for_date date,
    task_title text,
    task_location text,
    resolved_at timestamp without time zone,
    resolved_by text,
    htx_code character varying(20) NOT NULL,
    created_at timestamp without time zone NOT NULL,
    updated_at timestamp without time zone NOT NULL,
    CONSTRAINT "PK_automation_suggestions" PRIMARY KEY (id),
    CONSTRAINT "FK_automation_suggestions_employees_employee_id" FOREIGN KEY (employee_id) REFERENCES app_staff_work.employees (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS app_staff_work.recurring_tasks (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    title character varying(200) NOT NULL,
    description text,
    location text,
    priority text NOT NULL,
    department_id integer,
    preferred_assignee_id integer,
    weekdays character varying(20) NOT NULL,
    start_minute integer NOT NULL,
    due_minute integer NOT NULL,
    auto_assign boolean NOT NULL,
    is_active boolean NOT NULL,
    last_generated_on date,
    htx_code character varying(20) NOT NULL,
    created_at timestamp without time zone NOT NULL,
    updated_at timestamp without time zone NOT NULL,
    CONSTRAINT "PK_recurring_tasks" PRIMARY KEY (id),
    CONSTRAINT "FK_recurring_tasks_departments_department_id" FOREIGN KEY (department_id) REFERENCES app_staff_work.departments (id) ON DELETE SET NULL,
    CONSTRAINT "FK_recurring_tasks_employees_preferred_assignee_id" FOREIGN KEY (preferred_assignee_id) REFERENCES app_staff_work.employees (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "IX_automation_logs_htx_code_created_at" ON app_staff_work.automation_logs (htx_code, created_at);
CREATE INDEX IF NOT EXISTS "IX_automation_suggestions_employee_id" ON app_staff_work.automation_suggestions (employee_id);
CREATE INDEX IF NOT EXISTS "IX_automation_suggestions_htx_code_status" ON app_staff_work.automation_suggestions (htx_code, status);
CREATE INDEX IF NOT EXISTS "IX_recurring_tasks_department_id" ON app_staff_work.recurring_tasks (department_id);
CREATE INDEX IF NOT EXISTS "IX_recurring_tasks_preferred_assignee_id" ON app_staff_work.recurring_tasks (preferred_assignee_id);
