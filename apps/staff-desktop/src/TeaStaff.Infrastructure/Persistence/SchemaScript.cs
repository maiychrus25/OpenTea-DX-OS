using Microsoft.EntityFrameworkCore;
using TeaStaff.Infrastructure.Identity;

namespace TeaStaff.Infrastructure.Persistence;

/// <summary>Generates the PostgreSQL DDL for the DX-OS schema <c>app_staff_work</c> without a live database.</summary>
public static class SchemaScript
{
    public static string ForPostgres()
    {
        AppContext.SetSwitch("Npgsql.EnableLegacyTimestampBehavior", true);
        var config = new AppConfig { Database = { Provider = DatabaseProvider.Postgres } };
        var options = new DbContextOptionsBuilder<AppDbContext>()
            .UseNpgsql("Host=localhost;Database=agrimarket")
            .Options;
        using var db = new AppDbContext(options, new TenantContext(config), config.Database);
        return "-- SPDX-License-Identifier: MIT\n" +
               "-- Generated by: TeaStaffManager.exe --postgres-script <file>\n" +
               "-- Run as the app role inside its own schema (DX-OS mini-app convention: every table has htx_code).\n" +
               "CREATE SCHEMA IF NOT EXISTS app_staff_work;\n\n" +
               db.Database.GenerateCreateScript();
    }
}
